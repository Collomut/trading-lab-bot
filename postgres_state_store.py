"""PostgreSQL-backed state store and guarded one-time SQLite import.

Database access is server-side only. Tables live in the non-Data-API schema
bot_private. The source SQLite database and JSONL history are never deleted.
"""
from __future__ import annotations

import hashlib
import json
import sqlite3
import time
from datetime import datetime, timezone
from pathlib import Path

from psycopg import sql
from psycopg.conninfo import conninfo_to_dict, make_conninfo
from psycopg.rows import dict_row
from psycopg.types.json import Jsonb
from psycopg_pool import ConnectionPool


class PostgresStateStore:
    SCHEMA_VERSION = 1
    ORDER_TRANSITIONS = {
        "PENDING": {"SUBMITTED", "UNKNOWN", "REJECTED"},
        "SUBMITTED": {"UNKNOWN", "OPEN", "PARTIALLY_FILLED", "PARTIAL_CLOSED", "FILLED", "CANCELED", "REJECTED", "EXPIRED"},
        "UNKNOWN": {"UNKNOWN", "OPEN", "PARTIALLY_FILLED", "PARTIAL_CLOSED", "FILLED", "CANCELED", "REJECTED", "EXPIRED"},
        "OPEN": {"UNKNOWN", "OPEN", "PARTIALLY_FILLED", "PARTIAL_CLOSED", "FILLED", "CANCELED", "REJECTED", "EXPIRED"},
        "PARTIALLY_FILLED": {"UNKNOWN", "PARTIALLY_FILLED", "PARTIAL_CLOSED", "FILLED", "CANCELED", "REJECTED", "EXPIRED"},
    }
    TERMINAL = {"FILLED", "PARTIAL_CLOSED", "CANCELED", "REJECTED", "EXPIRED"}
    S = "bot_private"

    def __init__(self, database_url: str, *, require_import: bool = True):
        if not database_url:
            raise ValueError("DATABASE_URL is required")
        conninfo = conninfo_to_dict(database_url)
        if str(conninfo.get("port", "5432")) == "6543":
            raise ValueError("Supabase transaction pooler is not supported; use direct or session mode")
        conninfo.setdefault("sslmode", "require")
        self._pool = ConnectionPool(
            conninfo=make_conninfo(**conninfo),
            min_size=1,
            max_size=4,
            timeout=10,
            kwargs={"row_factory": dict_row, "connect_timeout": 10},
            open=True,
        )
        if not require_import:
            self._initialize()
        if require_import:
            with self._pool.connection() as conn:
                marker = conn.execute(
                    "SELECT 1 FROM bot_private.storage_migrations WHERE id=1"
                ).fetchone()
            if marker is None:
                self.close()
                raise RuntimeError(
                    "Supabase has no verified SQLite import marker; refusing to start the bot"
                )

    def close(self):
        self._pool.close()

    def _initialize(self):
        # Private schema avoids accidental exposure through Supabase's default Data API schema.
        with self._pool.connection() as conn, conn.transaction():
            conn.execute("CREATE SCHEMA IF NOT EXISTS bot_private")
            schema_sql = """
                CREATE TABLE IF NOT EXISTS bot_private.schema_migrations (
                    version INTEGER PRIMARY KEY, applied_at TEXT NOT NULL,
                    description TEXT NOT NULL
                );
                CREATE TABLE IF NOT EXISTS bot_private.state (
                    key TEXT PRIMARY KEY, value_json JSONB NOT NULL
                );
                CREATE TABLE IF NOT EXISTS bot_private.positions (
                    symbol TEXT PRIMARY KEY, value_json JSONB NOT NULL
                );
                CREATE TABLE IF NOT EXISTS bot_private.order_intents (
                    client_order_id TEXT PRIMARY KEY, symbol TEXT NOT NULL, side TEXT NOT NULL,
                    amount TEXT NOT NULL, state TEXT NOT NULL, exchange_order_id TEXT,
                    filled TEXT NOT NULL DEFAULT '0', average TEXT, request_json JSONB NOT NULL,
                    response_json JSONB, applied BOOLEAN NOT NULL DEFAULT FALSE,
                    created_at TEXT NOT NULL, updated_at TEXT NOT NULL
                );
                CREATE INDEX IF NOT EXISTS order_intents_state_created_idx
                    ON bot_private.order_intents (state, created_at);
                CREATE TABLE IF NOT EXISTS bot_private.audit_events (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    event_type TEXT NOT NULL, details_json JSONB NOT NULL,
                    created_at TEXT NOT NULL
                );
                CREATE INDEX IF NOT EXISTS audit_events_type_id_idx
                    ON bot_private.audit_events (event_type, id DESC);
                CREATE TABLE IF NOT EXISTS bot_private.trades (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    source_id TEXT NOT NULL UNIQUE, payload JSONB NOT NULL,
                    created_at TEXT NOT NULL
                );
                CREATE TABLE IF NOT EXISTS bot_private.storage_migrations (
                    id INTEGER PRIMARY KEY CHECK (id=1),
                    source_sha256 TEXT NOT NULL, counts_json JSONB NOT NULL,
                    completed_at TEXT NOT NULL
                );
            """
            for statement in schema_sql.split(";"):
                if statement.strip():
                    conn.execute(statement)

    @classmethod
    def migrate_from_sqlite(cls, database_url: str, sqlite_path: str | Path, trades_path: str | Path):
        """Back up and import the stopped SQLite store plus JSONL trade history atomically."""
        source = Path(sqlite_path)
        if not source.is_file():
            raise FileNotFoundError("SQLite source database is missing; import was not attempted")
        # Repeated deploys must not create backups or re-import once cutover succeeded.
        check = cls(database_url, require_import=False)
        try:
            with check._pool.connection() as conn:
                marker = conn.execute(
                    "SELECT counts_json FROM bot_private.storage_migrations WHERE id=1"
                ).fetchone()
            if marker:
                return {"status": "already_imported", "counts": marker["counts_json"],
                        "backup": "original SQLite and first-import backup retained"}
        finally:
            check.close()
        # A stable online backup remains on the Railway volume for rollback/audit.
        stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
        backup = source.with_name(f"{source.stem}_pre_supabase_{stamp}{source.suffix}")
        with sqlite3.connect(source) as src, sqlite3.connect(backup) as dst:
            src.backup(dst)
        digest = hashlib.sha256(backup.read_bytes()).hexdigest()

        sqlite_rows = {}
        with sqlite3.connect(backup) as src:
            src.row_factory = sqlite3.Row
            tables = {r["name"] for r in src.execute(
                "SELECT name FROM sqlite_master WHERE type='table'"
            )}
            required = {"schema_migrations", "state", "positions", "order_intents", "audit_events"}
            if not required.issubset(tables):
                raise RuntimeError("SQLite source schema is incomplete; import refused")
            for table in sorted(required):
                sqlite_rows[table] = [dict(row) for row in src.execute(f"SELECT * FROM {table}")]
            quick = src.execute("PRAGMA quick_check").fetchone()[0]
            if quick != "ok":
                raise RuntimeError("SQLite integrity check failed; import refused")

        trade_rows = []
        trade_file = Path(trades_path)
        if trade_file.exists():
            with trade_file.open("r", encoding="utf-8") as f:
                for line_number, raw in enumerate(f, start=1):
                    if not raw.strip():
                        continue
                    try:
                        payload = json.loads(raw)
                        json.dumps(payload, allow_nan=False)
                    except (ValueError, TypeError) as exc:
                        raise RuntimeError(
                            f"Trade history line {line_number} is invalid; import refused"
                        ) from exc
                    trade_rows.append((f"sqlite-jsonl:{line_number}", payload,
                                       str(payload.get("timestamp") or cls._now())))

        store = cls(database_url, require_import=False)
        counts = {key: len(rows) for key, rows in sqlite_rows.items()}
        counts["trades"] = len(trade_rows)
        try:
            with store._pool.connection() as conn, conn.transaction():
                marker = conn.execute(
                    "SELECT source_sha256,counts_json FROM bot_private.storage_migrations WHERE id=1"
                ).fetchone()
                if marker:
                    if marker["source_sha256"] != digest:
                        raise RuntimeError("Supabase was already imported from a different SQLite snapshot")
                    return {"status": "already_imported", "counts": marker["counts_json"], "backup": str(backup)}

                existing = conn.execute("""
                    SELECT
                      (SELECT COUNT(*) FROM bot_private.state) +
                      (SELECT COUNT(*) FROM bot_private.positions) +
                      (SELECT COUNT(*) FROM bot_private.order_intents) +
                      (SELECT COUNT(*) FROM bot_private.audit_events) +
                      (SELECT COUNT(*) FROM bot_private.trades) AS n
                """).fetchone()["n"]
                if existing:
                    raise RuntimeError("Supabase has unmarked data; refusing to merge or overwrite it")

                for row in sqlite_rows["schema_migrations"]:
                    conn.execute(
                        "INSERT INTO bot_private.schema_migrations(version,applied_at,description) VALUES(%s,%s,%s)",
                        (row["version"], row["applied_at"], row["description"]),
                    )
                for row in sqlite_rows["state"]:
                    conn.execute(
                        "INSERT INTO bot_private.state(key,value_json) VALUES(%s,%s::jsonb)",
                        (row["key"], row["value_json"]),
                    )
                for row in sqlite_rows["positions"]:
                    conn.execute(
                        "INSERT INTO bot_private.positions(symbol,value_json) VALUES(%s,%s::jsonb)",
                        (row["symbol"], row["value_json"]),
                    )
                for row in sqlite_rows["order_intents"]:
                    conn.execute("""
                        INSERT INTO bot_private.order_intents
                        (client_order_id,symbol,side,amount,state,exchange_order_id,filled,average,
                         request_json,response_json,applied,created_at,updated_at)
                        VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s::jsonb,%s::jsonb,%s,%s,%s)
                    """, (row["client_order_id"], row["symbol"], row["side"], row["amount"],
                          row["state"], row["exchange_order_id"], row["filled"], row["average"],
                          row["request_json"], row["response_json"], bool(row["applied"]),
                          row["created_at"], row["updated_at"]))
                for row in sqlite_rows["audit_events"]:
                    conn.execute("""
                        INSERT INTO bot_private.audit_events(id,event_type,details_json,created_at)
                        VALUES(%s,%s,%s::jsonb,%s)
                    """, (row["id"], row["event_type"], row["details_json"], row["created_at"]))
                for source_id, payload, created_at in trade_rows:
                    conn.execute("""
                        INSERT INTO bot_private.trades(source_id,payload,created_at)
                        VALUES(%s,%s,%s)
                    """, (source_id, Jsonb(payload), created_at))
                conn.execute("""
                    SELECT setval(pg_get_serial_sequence('bot_private.audit_events','id'),
                                  GREATEST(COALESCE((SELECT MAX(id) FROM bot_private.audit_events),1),1),
                                  EXISTS(SELECT 1 FROM bot_private.audit_events))
                """)
                conn.execute("""
                    SELECT setval(pg_get_serial_sequence('bot_private.trades','id'),
                                  GREATEST(COALESCE((SELECT MAX(id) FROM bot_private.trades),1),1),
                                  EXISTS(SELECT 1 FROM bot_private.trades))
                """)
                conn.execute("""
                    INSERT INTO bot_private.storage_migrations(id,source_sha256,counts_json,completed_at)
                    VALUES(1,%s,%s,%s)
                """, (digest, Jsonb(counts), cls._now()))
            return {"status": "imported", "counts": counts, "backup": str(backup)}
        finally:
            store.close()

    @staticmethod
    def _now():
        return datetime.now(timezone.utc).isoformat()

    def get_schema_version(self):
        with self._pool.connection() as conn:
            row = conn.execute("SELECT MAX(version) AS version FROM bot_private.schema_migrations").fetchone()
            return int(row["version"] or 0)

    def quick_check(self):
        with self._pool.connection() as conn:
            conn.execute("SELECT 1")
        return "ok"

    def read_state(self, key):
        with self._pool.connection() as conn:
            row = conn.execute("SELECT value_json FROM bot_private.state WHERE key=%s", (key,)).fetchone()
            return row["value_json"] if row else None

    def write_state(self, key, value):
        encoded = json.dumps(value, allow_nan=False, separators=(",", ":"))
        with self._pool.connection() as conn, conn.transaction():
            conn.execute("""
                INSERT INTO bot_private.state(key,value_json) VALUES(%s,%s::jsonb)
                ON CONFLICT(key) DO UPDATE SET value_json=EXCLUDED.value_json
            """, (key, encoded))

    def read_positions(self):
        with self._pool.connection() as conn:
            rows = conn.execute("SELECT symbol,value_json FROM bot_private.positions ORDER BY symbol").fetchall()
            return {r["symbol"]: r["value_json"] for r in rows}

    def write_positions(self, positions):
        encoded = [(symbol, json.dumps(value, allow_nan=False, separators=(",", ":")))
                   for symbol, value in positions.items()]
        with self._pool.connection() as conn, conn.transaction():
            conn.execute("DELETE FROM bot_private.positions")
            for symbol, value in encoded:
                conn.execute("INSERT INTO bot_private.positions(symbol,value_json) VALUES(%s,%s::jsonb)",
                             (symbol, value))

    def create_order_intent(self, client_order_id, symbol, side, amount, request):
        with self._pool.connection() as conn, conn.transaction():
            conn.execute("""
                INSERT INTO bot_private.order_intents(client_order_id,symbol,side,amount,state,request_json,created_at,updated_at)
                VALUES(%s,%s,%s,%s,'PENDING',%s,%s,%s)
            """, (client_order_id, symbol, side.upper(), str(amount),
                  Jsonb(request), self._now(), self._now()))
        try:
            self.append_event("order_status", {"symbol": symbol, "side": side.lower(),
                                               "amount": str(amount), "state": "PENDING"})
        except Exception:
            pass

    def update_order(self, client_order_id, state, *, exchange_order_id=None, filled=None, average=None, response=None):
        with self._pool.connection() as conn, conn.transaction():
            row = conn.execute(
                "SELECT * FROM bot_private.order_intents WHERE client_order_id=%s FOR UPDATE",
                (client_order_id,),
            ).fetchone()
            if not row or state not in self.ORDER_TRANSITIONS.get(row["state"], set()):
                raise ValueError("Invalid or missing order-state transition")
            conn.execute("""
                UPDATE bot_private.order_intents SET state=%s,
                  exchange_order_id=COALESCE(%s,exchange_order_id),
                  filled=COALESCE(%s,filled), average=COALESCE(%s,average),
                  response_json=COALESCE(%s::jsonb,response_json), updated_at=%s
                WHERE client_order_id=%s
            """, (state, exchange_order_id, str(filled) if filled is not None else None,
                  str(average) if average is not None else None,
                  json.dumps(response, allow_nan=False) if response is not None else None,
                  self._now(), client_order_id))
        details = {"symbol": row["symbol"], "side": row["side"].lower(),
                   "amount": row["amount"], "state": state}
        if filled is not None:
            details["filled"] = str(filled)
        if average is not None:
            details["average"] = str(average)
        try:
            self.append_event("order_status", details)
        except Exception:
            pass

    def get_order(self, client_order_id):
        with self._pool.connection() as conn:
            return conn.execute(
                "SELECT * FROM bot_private.order_intents WHERE client_order_id=%s",
                (client_order_id,),
            ).fetchone()

    def is_known_client_order(self, client_order_id):
        if not client_order_id:
            return False
        with self._pool.connection() as conn:
            return conn.execute(
                "SELECT 1 FROM bot_private.order_intents WHERE client_order_id=%s",
                (client_order_id,),
            ).fetchone() is not None

    def mark_order_applied(self, client_order_id):
        with self._pool.connection() as conn, conn.transaction():
            cur = conn.execute("""
                UPDATE bot_private.order_intents SET applied=TRUE,updated_at=%s
                WHERE client_order_id=%s
                  AND state IN ('FILLED','PARTIAL_CLOSED','CANCELED','REJECTED','EXPIRED')
            """, (self._now(), client_order_id))
            if cur.rowcount != 1:
                raise ValueError("Only terminal orders can be marked applied")

    def unresolved_orders(self):
        with self._pool.connection() as conn:
            return conn.execute("""
                SELECT * FROM bot_private.order_intents
                WHERE state NOT IN ('FILLED','PARTIAL_CLOSED','CANCELED','REJECTED','EXPIRED')
                   OR applied=FALSE ORDER BY created_at
            """).fetchall()

    def append_event(self, event_type, details):
        encoded = json.dumps(details, allow_nan=False, separators=(",", ":"))
        with self._pool.connection() as conn, conn.transaction():
            conn.execute(
                "INSERT INTO bot_private.audit_events(event_type,details_json,created_at) VALUES(%s,%s::jsonb,%s)",
                (event_type, encoded, self._now()),
            )
            if event_type == "market_check":
                conn.execute("""
                    DELETE FROM bot_private.audit_events
                    WHERE event_type='market_check' AND id NOT IN (
                      SELECT id FROM bot_private.audit_events
                      WHERE event_type='market_check' ORDER BY id DESC LIMIT 20000
                    )
                """)

    def list_events(self, limit=100, *, event_type=None, exclude_event_type=None):
        limit = max(1, min(int(limit), 200))
        with self._pool.connection() as conn:
            if event_type is not None:
                rows = conn.execute("""
                    SELECT id,event_type,details_json,created_at FROM bot_private.audit_events
                    WHERE event_type=%s ORDER BY id DESC LIMIT %s
                """, (event_type, limit)).fetchall()
            elif exclude_event_type is not None:
                rows = conn.execute("""
                    SELECT id,event_type,details_json,created_at FROM bot_private.audit_events
                    WHERE event_type<>%s ORDER BY id DESC LIMIT %s
                """, (exclude_event_type, limit)).fetchall()
            else:
                rows = conn.execute("""
                    SELECT id,event_type,details_json,created_at FROM bot_private.audit_events
                    ORDER BY id DESC LIMIT %s
                """, (limit,)).fetchall()
        return [{"id": r["id"], "event_type": r["event_type"],
                 "details": r["details_json"], "created_at": r["created_at"]} for r in rows]

    
    def create_backup(self, backup_path: str | Path | None = None) -> Path:
        """Write a point-in-time JSON export of all persistent state tables."""
        if backup_path is None:
            stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
            backup_path = Path.cwd() / f"bot_state_postgres_backup_{stamp}.json"
        backup_path = Path(backup_path)
        backup_path.parent.mkdir(parents=True, exist_ok=True)
        with self._pool.connection() as conn:
            snapshot = {}
            for table, order in (
                ("schema_migrations", "version"),
                ("state", "key"),
                ("positions", "symbol"),
                ("order_intents", "created_at"),
                ("audit_events", "id"),
                ("trades", "id"),
            ):
                snapshot[table] = conn.execute(
                    sql.SQL("SELECT * FROM bot_private.{} ORDER BY {}").format(
                        sql.Identifier(table), sql.Identifier(order)
                    )
                ).fetchall()
        backup_path.write_text(json.dumps(snapshot, indent=2, default=str), encoding="utf-8")
        return backup_path

    def snapshot_and_reset_for_testnet_wipe(self, operator_reason: str, export_path=None) -> dict:
        """Record a backup and atomically reset Testnet-specific positions/order state."""
        if not operator_reason or not operator_reason.strip():
            raise ValueError("Operator reason is required for Testnet reset recovery")
        backup_file = self.create_backup()
        positions = self.read_positions()
        unresolved = self.unresolved_orders()
        export_data = {
            "timestamp": int(time.time() * 1000),
            "operator_reason": operator_reason.strip(),
            "backup_file": str(backup_file),
            "positions": positions,
            "unresolved_orders": unresolved,
        }
        if export_path:
            Path(export_path).write_text(json.dumps(export_data, indent=2, default=str), encoding="utf-8")
        with self._pool.connection() as conn, conn.transaction():
            conn.execute("DELETE FROM bot_private.positions")
            conn.execute("""
                UPDATE bot_private.order_intents SET state='CANCELED',applied=TRUE,updated_at=%s
                WHERE state NOT IN ('FILLED','PARTIAL_CLOSED','CANCELED','REJECTED','EXPIRED')
                   OR applied=FALSE
            """, (self._now(),))
            conn.execute("""
                DELETE FROM bot_private.state
                WHERE key IN ('baseline_asset_balances','testnet_smoke_trade')
            """)
            conn.execute(
                "INSERT INTO bot_private.audit_events(event_type,details_json,created_at) VALUES(%s,%s,%s)",
                ("testnet_reset_recovery", Jsonb(export_data), self._now()),
            )
        return export_data

    def append_trade(self, trade):
        payload = json.dumps(trade, allow_nan=False, separators=(",", ":"))
        created_at = str(trade.get("timestamp") or self._now())
        source_id = "runtime:" + hashlib.sha256(payload.encode("utf-8")).hexdigest()
        with self._pool.connection() as conn, conn.transaction():
            conn.execute("""
                INSERT INTO bot_private.trades(source_id,payload,created_at) VALUES(%s,%s::jsonb,%s)
                ON CONFLICT(source_id) DO NOTHING
            """, (source_id, payload, created_at))

    def list_trades(self, limit=5000):
        limit = max(1, min(int(limit), 20000))
        with self._pool.connection() as conn:
            rows = conn.execute(
                "SELECT payload FROM bot_private.trades ORDER BY id DESC LIMIT %s", (limit,)
            ).fetchall()
        return [r["payload"] for r in reversed(rows)]
